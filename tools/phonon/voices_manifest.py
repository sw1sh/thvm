"""voices_manifest.py: writes wl/THVMLink/Kernel/NN/Examples/Phonon/PhononVoices.wl, the table of the
English voices of Gradium's voice catalogue for Phonon (gradium/phonon-voices, Apache 2.0).

    python tools/phonon/voices_manifest.py [revision] > wl/THVMLink/Kernel/NN/Examples/Phonon/PhononVoices.wl

The catalogue's voices.jsonl gives each voice's name, identifier, locale, gender, age and description; the
repository's file list gives each voice file's size and SHA-256.  Without a revision the repository's
current one is taken, and the file pins it.  Needs only the standard library.
"""
import json, sys, urllib.request

REPO = "gradium/phonon-voices"
info = json.load(urllib.request.urlopen(f"https://huggingface.co/api/models/{REPO}?blobs=true"))
revision = sys.argv[1] if len(sys.argv) > 1 else info["sha"]
if revision != info["sha"]:
    info = json.load(urllib.request.urlopen(f"https://huggingface.co/api/models/{REPO}/revision/{revision}?blobs=true"))
files = {s["rfilename"]: s for s in info["siblings"]}
index = urllib.request.urlopen(f"https://huggingface.co/{REPO}/resolve/{revision}/voices.jsonl").read().decode()
voices = [v for v in (json.loads(line) for line in index.splitlines() if line.strip()) if v["language"] == "en"]
sizes = {files[v["filename"]]["size"] for v in voices}
assert len(sizes) == 1, sizes
assert len({v["name"] for v in voices}) == len(voices)


def wl(s):
    """A Wolfram Language string literal in ASCII."""
    out = []
    for c in s:
        if c in '"\\':
            out.append("\\" + c)
        elif ord(c) < 128:
            out.append(c)
        else:
            out.append("\\:%04x" % ord(c))
    return '"' + "".join(out) + '"'


rows = []
for v in voices:
    f = files[v["filename"]]
    assert v["filename"] == "voices/" + v["voice_id"] + ".safetensors", v["filename"]
    rows.append("    {%s}" % ", ".join([
        wl(v["name"]), wl(v["voice_id"]), wl(v["locale"]), wl(v["gender"]) if v.get("gender") else "None",
        wl(v["age"]) if v.get("age") else "None", wl(f["lfs"]["sha256"]), wl(" ".join(v["description"].split()))]))

locales = sorted({v["locale"] for v in voices})
print('''(* PhononVoices.wl -- the English voices of Gradium's voice catalogue for Phonon.

   The catalogue is %s (Apache 2.0); these are its %d voices of the locales
   %s.  Each is a file of voice frames in the format of the model's default voice,
   fetched from the catalogue on first use and checked against the SHA-256 here.

   Generated by tools/phonon/voices_manifest.py from the catalogue's voices.jsonl and file list at the
   revision below: edit the generator, not this file.  The descriptions are the catalogue's own. *)

BeginPackage["WolframInstitute`THVMLink`Examples`", {"WolframInstitute`THVMLink`"}];

Begin["`Private`"];

$phVoiceRepository = "%s";
$phVoiceRevision = "%s";
$phVoiceBytes = %d;

(* {name, identifier, locale, gender, age, SHA-256 of voices/identifier.safetensors, description} *)
$phVoiceTable = {
%s
};

End[];

EndPackage[];''' % (REPO, len(voices), ", ".join(locales), REPO, revision, sizes.pop(), ",\n".join(rows)))
